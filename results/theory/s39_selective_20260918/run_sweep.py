#!/usr/bin/env python3
"""Sweep of selective_decay_trace.py: every variant on a FAMILY of baselines (the stock refresh rule is chaotic in level
placement -- the repository conventions "Instruments that lie" -- so a delta read on one baseline can be a fluke; the family shows its spread).
Writes SWEEP.json and SWEEP.md (tables only; the reading is in SELECTIVE_DECAY_COST_20260918.md)."""
import json, os, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); TOOL = os.path.join(HERE, "selective_decay_trace.py")
DROPS = ["--drop-wv", "7", "--drop-wkr", "4", "--drop-wout", "7", "--drop-win", "4"]
BASES = [
    ("DEMO: lanes-block, X8 drops, robust 8 (take 9 / A11: record 480 boots)", ["--lanes-block", "--robust-iters", "8"] + DROPS),
    ("LONG-RUN PLAN: lanes-block, X8 drops, robust 12", ["--lanes-block", "--robust-iters", "12"] + DROPS),
    ("lanes-block, X8 drops, bundle Newton (record 404 boots)", ["--lanes-block"] + DROPS),
    ("lanes-block, no drops, bundle Newton (record 380 boots)", ["--lanes-block"]),
    ("SCHEDULED: lanes-block, parent-first + share-babies + late-margin, bundle Newton", ["--lanes-block", "--schedule", "parent-first", "--share-babies", "--late-margin"]),
    ("SCHEDULED + robust 8", ["--lanes-block", "--schedule", "parent-first", "--share-babies", "--late-margin", "--robust-iters", "8"]),
]
VARIANTS = [
    ("fixed coefficients (today's model)", []),
    ("diagonal selective decay, degree-2 gate", ["--sel", "diag"]),
    ("diagonal selective decay, degree-4 gate", ["--sel", "diag", "--sel-poly", "2"]),
    ("projected selective decay (one d->d matvec per layer)", ["--sel", "proj"]),
    ("low-rank selective decay (d->64->d; rectangular matvec: projection)", ["--sel", "lowrank"]),
    ("input gate only (S3.8 Vector A)", ["--input-gate"]),
    ("RG-LRU pair: projected decay + input gate", ["--sel", "proj", "--input-gate"]),
    ("state width N = 2, fixed coefficients", ["--state-width", "2"]),
    ("state width N = 4, fixed coefficients", ["--state-width", "4"]),
    ("state width N = 16, fixed coefficients", ["--state-width", "16"]),
    ("N = 16 + diagonal selective decay", ["--sel", "diag", "--state-width", "16"]),
    ("Mamba-shaped time-mix INSIDE our block: N = 16, low-rank Delta (deg 4), exp ladder (deg 4), selective B/C, conv 4", ["--sel", "lowrank", "--sel-poly", "2", "--decay-exp", "2", "--state-width", "16", "--bc-selective", "--conv", "4"]),
]
KEYS = ["boots_total", "boots_stock_rule", "canon_boots", "carried_cts", "rot", "ctct", "ctpt_elem", "matvec_chunks", "diag_limbs"]
out = {"bases": []}; tmp = os.path.join(tempfile.mkdtemp(), "o.json")
for bname, bargs in BASES:
    rows = []
    for vname, vargs in VARIANTS:
        subprocess.run([sys.executable, TOOL, "--ticks", "5", "--json", tmp] + bargs + vargs, check=True, capture_output=True)
        pt = json.load(open(tmp))["per_tick"]; last = pt[-1]
        rows.append({"variant": vname, "args": vargs, **{k: last[k] for k in KEYS}, "boots_by_tick": [r["boots_total"] for r in pt],
                     "period1": len({r["boots_total"] for r in pt[1:]}) == 1})
    out["bases"].append({"base": bname, "args": bargs, "rows": rows})
json.dump(out, open(os.path.join(HERE, "SWEEP.json"), "w"), indent=1)
with open(os.path.join(HERE, "SWEEP.md"), "w") as f:
    f.write("# selective_decay_trace.py sweep (REPLAY, not a measurement; generated by run_sweep.py)\n\n")
    for b in out["bases"]:
        r0 = b["rows"][0]
        f.write(f"## {b['base']}\n\n`{' '.join(b['args'])}`\n\n| variant | boots/tick | delta boots | of which carry boots | carried cts | rotations | ct x ct | ct x pt elem | matvecs | Lambda (limb-diagonals) | same every tick |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
        for r in b["rows"]:
            f.write(f"| {r['variant']} | {r['boots_total']} | {r['boots_total'] - r0['boots_total']:+d} | {r['canon_boots']} | {r['carried_cts']} | {r['rot']} ({r['rot'] - r0['rot']:+d}) | {r['ctct']} ({r['ctct'] - r0['ctct']:+d}) | "
                    f"{r['ctpt_elem']} ({r['ctpt_elem'] - r0['ctpt_elem']:+d}) | {r['matvec_chunks']} | {r['diag_limbs']} ({r['diag_limbs'] - r0['diag_limbs']:+d}) | {r['period1']} |\n")
        f.write("\n")
print(open(os.path.join(HERE, "SWEEP.md")).read())
